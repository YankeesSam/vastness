#!/usr/bin/env node
// Runtime dependency check (T-003, VN-GEN-005, VN-GEN-007).
//   node scripts/check-deps.mjs          check: allowlist, licences, THIRD_PARTY_NOTICES.txt is current
//   node scripts/check-deps.mjs --write  regenerate THIRD_PARTY_NOTICES.txt
// The allowlist is the "Runtime dependencies" line of docs/adr/0001-stack.md, so amending the ADR is the only way
// to add one. Runtime packages (direct and transitive) are the lock file's entries not marked dev.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

/** Permissive licences acceptable for code bundled into an Apache-2.0 app. */
export const ALLOWED_LICENCES = ["0BSD", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "MIT"];

/** Package names in backticks on ADR-0001's "Runtime dependencies" line, sorted. */
export function allowlistFromAdr(adr) {
  const line = adr.split("\n").find((l) => l.includes("**Runtime dependencies"));
  if (!line) throw new Error("ADR-0001 has no Runtime dependencies line");
  return [...line.split(":**")[1].matchAll(/`([^`]+)`/g)].map((m) => m[1]).sort();
}

/** Entries of package.json `dependencies` missing from the allowlist, sorted. */
export function disallowed(dependencies, allowlist) {
  return Object.keys(dependencies ?? {})
    .filter((d) => !allowlist.includes(d))
    .sort();
}

/** Non-dev packages of an npm v2/v3 lock file, sorted by name then version. */
export function runtimePackages(lock) {
  const out = [];
  for (const [path, entry] of Object.entries(lock.packages ?? {})) {
    if (path === "" || entry.dev || entry.devOptional || entry.link) continue;
    const name = path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
    const pkg = { name, version: entry.version };
    if (entry.license) pkg.license = entry.license;
    out.push(pkg);
  }
  return out.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : a.version < b.version ? -1 : 1));
}

/** "name: licence" for each package whose licence is missing or not in ALLOWED_LICENCES. */
export function badLicences(packages) {
  const ok = (expr) => {
    // SPDX "A OR B" passes when any option is allowed; "A AND B" needs all.
    const e = expr.replace(/[()]/g, "").trim();
    if (e.includes(" OR ")) return e.split(" OR ").some((p) => ok(p));
    if (e.includes(" AND ")) return e.split(" AND ").every((p) => ok(p));
    return ALLOWED_LICENCES.includes(e);
  };
  return packages.filter((p) => !p.license || !ok(p.license)).map((p) => `${p.name}: ${p.license ?? "(none)"}`);
}

/** THIRD_PARTY_NOTICES.txt text: sorted, LF only, no dates. */
export function renderNotices(packages) {
  const sorted = [...packages].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const rule = "-".repeat(78);
  const parts = [
    "Vastness: third-party notices",
    "",
    "The Vastness web app bundles the following packages. Each is listed with its licence text.",
    "Generated by scripts/check-deps.mjs --write; do not edit by hand.",
  ];
  for (const p of sorted) {
    parts.push("", rule, `${p.name} ${p.version} (${p.license})`, rule, "", p.text.replace(/\r\n?/g, "\n").trimEnd());
  }
  return parts.join("\n") + "\n";
}

/** Licence text from node_modules, or a pointer to the SPDX text when the package ships none. */
function licenceText(root, name, license) {
  const dir = join(root, "node_modules", name);
  const file = existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f))
        .sort()[0]
    : undefined;
  if (file) return readFileSync(join(dir, file), "utf8");
  return `No licence file in the package; see https://spdx.org/licenses/${license}.html`;
}

function main() {
  const root = fileURLToPath(new URL("../", import.meta.url));
  const read = (p) => readFileSync(join(root, p), "utf8");
  const write = process.argv.includes("--write");
  const errors = [];

  const allowlist = allowlistFromAdr(read("docs/adr/0001-stack.md"));
  const pkg = JSON.parse(read("package.json"));
  for (const d of disallowed(pkg.dependencies, allowlist)) {
    errors.push(`${d} is not an ADR-0001 runtime dependency (allowed: ${allowlist.join(", ")})`);
  }

  const packages = runtimePackages(JSON.parse(read("package-lock.json")));
  for (const p of packages) console.log(`${p.name}@${p.version} ${p.license ?? "(none)"}`);
  for (const b of badLicences(packages)) errors.push(`licence not allowed: ${b}`);

  const notices = renderNotices(packages.map((p) => ({ ...p, text: licenceText(root, p.name, p.license) })));
  const target = join(root, "THIRD_PARTY_NOTICES.txt");
  if (write) {
    writeFileSync(target, notices);
    console.log("wrote THIRD_PARTY_NOTICES.txt");
  } else if (!existsSync(target) || readFileSync(target, "utf8") !== notices) {
    errors.push("THIRD_PARTY_NOTICES.txt is stale: run node scripts/check-deps.mjs --write");
  }

  if (errors.length) {
    for (const e of errors) console.error(`check-deps: ${e}`);
    process.exit(1);
  }
  console.log(`check-deps: ok (${packages.length} runtime packages)`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
